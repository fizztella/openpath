def translate(language_code: str, text: str) -> str:
    """Translate interface text and fall back to English."""
    if not isinstance(text, str):
        return text
    direct = TRANSLATIONS.get(language_code, {}).get(text)
    if direct is not None:
        return direct
    match = re.fullmatch(r"IELTS is ([0-9.]+); ([0-9.]+) is required", text)
    if match and language_code == "ru":
        return f"IELTS: {match[1]}; требуется {match[2]}"
    match = re.fullmatch(
        r"First-year academic fees exceed the budget by \$([0-9,]+)", text
    )
    if match and language_code == "ru":
        return f"Стоимость первого года превышает бюджет на ${match[1]}"
    return text
